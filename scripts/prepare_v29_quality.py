"""v29 P2/P3 QuALITY data preparation (same-document multi-question prefix reuse).
select : deterministic article selection from the QuALITY validation split (>=16 questions, 4k-7k prefix tokens),
         shuffled with a fixed seed; first 12 = formal (3 stores x 4 slots), next 4 = pilot (1 store). No model output used.
bundles: per set (pilot, f0, f1, f2) and slot (sst2/subj/trec/rte are just storage slot names):
         eval/<slot>.jsonl      all real questions of that article (test)
         ctl_fit|ctl_val        64/64 questions sampled from OTHER (unselected) articles, asked against this article
synth  : document-conditioned synthetic calibration MCQs (64 fit + 64 val) generated by Qwen2.5-7B-Instruct with vLLM from
         article segments only; real questions of the article are never input. Overlap with real questions is only REPORTED.
Usage: prepare_v29_quality.py select | bundles | synth <set>"""
import hashlib, json, random, re, sys
from pathlib import Path
R = Path('/home/shensicheng/qyd/pans/src'); D = R / 'data/v29/quality'
SRC = Path('/home/shensicheng/qyd/pans/work/datasets/QuALITY/quality_validation.jsonl')
MODEL = '/home/shensicheng/qyd/pans/models/Qwen2.5-7B-Instruct'
USER, ASSIST = '<|im_start|>user\n', '<|im_end|>\n<|im_start|>assistant\n'
SLOTS = ['sst2', 'subj', 'trec', 'rte']; LETTERS = ['A', 'B', 'C', 'D']
norm = lambda s: ' '.join(s.casefold().split())
h = lambda s: hashlib.sha256(s.encode()).hexdigest()[:16]

def prefix_text(article):
    return USER + 'Read the following article. Then answer the multiple-choice question that follows it.\n\n' + article.strip() + '\n\n'
def query_text(q, options):
    return 'Question: ' + q.strip() + '\n' + ''.join(f'{L}. {o.strip()}\n' for L, o in zip(LETTERS, options)) + \
           'Answer with the letter of the correct option.' + ASSIST
def rows():
    return [json.loads(l) for l in SRC.read_text().splitlines() if l.strip()]

if sys.argv[1] == 'select':
    from transformers import AutoTokenizer
    tok = AutoTokenizer.from_pretrained(MODEL, local_files_only=True)
    by = {}
    for r in rows(): by.setdefault(r['article'], []).append(r)
    cand = []
    for art, qs in by.items():
        n = len(tok(prefix_text(art), add_special_tokens=False).input_ids)
        if len(qs) >= 16 and 4000 <= n <= 7000 and all(len(q['options']) == 4 for q in qs):
            cand.append(dict(article_hash=h(art), prefix_tokens=n, questions=len(qs), title=art.strip().split('\n')[0][:80]))
    cand.sort(key=lambda c: c['article_hash']); random.Random(2911).shuffle(cand)
    sets = {'f0': cand[0:4], 'f1': cand[4:8], 'f2': cand[8:12], 'pilot': cand[12:16]}
    D.mkdir(parents=True, exist_ok=False)
    (D / 'selection.json').write_text(json.dumps(dict(rule='validation split; >=16 questions; 4000-7000 prefix tokens; '
        'sorted by article hash then random.Random(2911).shuffle; f0-f2 formal (12), pilot (4)', candidates=len(cand),
        sets={k: [dict(c, slot=s) for c, s in zip(v, SLOTS)] for k, v in sets.items()}), indent=1))
    print('candidates', len(cand), {k: [(c['questions'], c['prefix_tokens']) for c in v] for k, v in sets.items()})

elif sys.argv[1] == 'bundles':
    sel = json.loads((D / 'selection.json').read_text())
    by = {}
    for r in rows(): by.setdefault(h(r['article']), []).append(r)
    chosen = {c['article_hash'] for v in sel['sets'].values() for c in v}
    pool = [r for k, v in by.items() if k not in chosen for r in v]
    random.Random(2912).shuffle(pool)
    audit = {}
    for set_name, items in sel['sets'].items():
        for c in items:
            qs = by[c['article_hash']]; art = qs[0]['article']; slot = c['slot']; pre = prefix_text(art)
            def rec(uid, q, opts, ans):
                return dict(uid=uid, task=slot, prefix_text=pre, query_text=query_text(q, opts),
                            answer=LETTERS[ans] if ans is not None else 'A', labels=LETTERS, label_continuation_prefix='')
            ev = [rec(f'quality-{c["article_hash"]}-q{i}', q['question'], q['options'], int(q['answer'])) for i, q in enumerate(qs)]
            rng = random.Random(f'2913:{c["article_hash"]}'); ctl = rng.sample(pool, 128)
            assert all(h(q['article']) not in chosen for q in ctl)
            ctl = [rec(f'quality-{c["article_hash"]}-ctl{i}', q['question'], q['options'], int(q['answer'])) for i, q in enumerate(ctl)]
            for role, part in (('eval', ev), ('ctl_fit', ctl[:64]), ('ctl_val', ctl[64:])):
                p = D / set_name / role / f'{slot}.jsonl'; p.parent.mkdir(parents=True, exist_ok=True)
                with p.open('x') as f: f.write(''.join(json.dumps(x, ensure_ascii=False) + '\n' for x in part))
            audit[f'{set_name}/{slot}'] = dict(article_hash=c['article_hash'], eval=len(ev), ctl=128,
                                               ctl_from_unselected_articles_only=True)
    (D / 'bundles_audit.json').write_text(json.dumps(audit, indent=1)); print(audit)

elif sys.argv[1] == 'synth':
    set_name = sys.argv[2]
    # vLLM in this venv fails to start (missing nixl_ep module) -> HF transformers batched sampling, same prompt/settings.
    import torch
    from transformers import AutoTokenizer, AutoModelForCausalLM
    sel = json.loads((D / 'selection.json').read_text())
    by = {}
    for r in rows(): by.setdefault(h(r['article']), []).append(r)
    tok = AutoTokenizer.from_pretrained(MODEL, local_files_only=True); tok.padding_side = 'left'
    model = AutoModelForCausalLM.from_pretrained(MODEL, dtype=torch.bfloat16, local_files_only=True).cuda().eval()
    torch.manual_seed(2914)
    sp = dict(do_sample=True, temperature=0.9, top_p=0.95, max_new_tokens=700, seed=2914, backend='transformers')
    class _Out:
        def __init__(self, t): self.outputs = [type('o', (), {'text': t})()]
    class _LLM:
        def generate(self, prompts, _sp, bs=8):
            res = []
            for i in range(0, len(prompts), bs):
                enc = tok(prompts[i:i + bs], return_tensors='pt', padding=True, add_special_tokens=False).to('cuda')
                with torch.no_grad():
                    out = model.generate(**enc, do_sample=True, temperature=0.9, top_p=0.95, max_new_tokens=700, pad_token_id=tok.eos_token_id)
                res += [_Out(tok.decode(o[enc.input_ids.shape[1]:], skip_special_tokens=True)) for o in out]
            return res
    llm = _LLM()
    audit = {}
    for c in sel['sets'][set_name]:
        qs = by[c['article_hash']]; art = qs[0]['article']; slot = c['slot']
        paras = [p for p in re.split(r'\n\s*\n', art) if p.strip()]
        segs, cur = [], ''
        for p in paras:  # ~350-token segments covering the whole article
            if cur and len(tok(cur + '\n\n' + p).input_ids) > 350: segs.append(cur); cur = p
            else: cur = (cur + '\n\n' + p) if cur else p
        if cur: segs.append(cur)
        def prompt(i):
            seg = segs[i % len(segs)]
            msg = ('Here is an excerpt from a longer story or article:\n\n' + seg + '\n\nWrite 4 different multiple-choice '
                   'reading-comprehension questions about this excerpt. Each question must have exactly 4 options. Some questions '
                   'may require inference. Output only JSON lines, one per question, like '
                   '{"question": "...", "options": ["...", "...", "...", "..."], "answer": 0}')
            return tok.apply_chat_template([{'role': 'user', 'content': msg}], tokenize=False, add_generation_prompt=True)
        got, seen, rounds = [], set(), 0
        while len(got) < 128 and rounds < 12:
            outs = llm.generate([prompt(i) for i in range(rounds * len(segs), (rounds + 1) * len(segs))], sp)
            for o in outs:
                for line in o.outputs[0].text.splitlines():
                    line = line.strip().strip(',')
                    if not line.startswith('{'): continue
                    try: j = json.loads(line)
                    except Exception: continue
                    if not isinstance(j.get('question'), str) or not isinstance(j.get('options'), list) or len(j['options']) != 4: continue
                    if not all(isinstance(x, str) and x.strip() for x in j['options']): continue
                    k = norm(j['question'])
                    if k in seen or len(k) < 12: continue
                    seen.add(k); got.append(j)
            rounds += 1
        assert len(got) >= 128, (c['article_hash'], len(got))
        random.Random(f'2915:{c["article_hash"]}').shuffle(got); got = got[:128]
        pre = prefix_text(art)
        recs = [dict(uid=f'quality-{c["article_hash"]}-syn{i}', task=slot, prefix_text=pre, query_text=query_text(j['question'], j['options']),
                     answer='A', labels=LETTERS, label_continuation_prefix='') for i, j in enumerate(got)]
        for role, part in (('syn_fit', recs[:64]), ('syn_val', recs[64:])):
            p = D / set_name / role / f'{slot}.jsonl'; p.parent.mkdir(parents=True, exist_ok=True)
            with p.open('x') as f: f.write(''.join(json.dumps(x, ensure_ascii=False) + '\n' for x in part))
        real = [norm(q['question']) for q in qs]
        def jac(a, b):
            A, B = set(a.split()), set(b.split()); return len(A & B) / max(1, len(A | B))
        audit[slot] = dict(article_hash=c['article_hash'], segments=len(segs), rounds=rounds, generated_unique=len(seen),
                           exact_overlap_with_real=sum(norm(j['question']) in real for j in got),
                           max_word_jaccard_with_real=max(jac(norm(j['question']), r) for j in got for r in real))
        print(slot, audit[slot], flush=True)
    (D / set_name / 'synth_audit.json').write_text(json.dumps(dict(model=MODEL, sampling=str(sp), note='answers of synthetic '
        'questions are NOT used: reader calibration fits teacher scores; answer field is a placeholder', articles=audit), indent=1))
